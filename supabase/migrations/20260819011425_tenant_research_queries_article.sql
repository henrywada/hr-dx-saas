-- =============================================================================
-- 検索履歴に条番号・通達番号を保持する列を追加
--
-- これが無いと「労働基準法 第36条」の検索を履歴から再実行したときに
-- 条番号が失われ、目次が返ってしまう（仕様の Should 要件「履歴から再実行できる」
-- が条文・通達番号指定の検索で機能しない）。
-- =============================================================================

ALTER TABLE public.tenant_research_queries
  ADD COLUMN IF NOT EXISTS article TEXT;

COMMENT ON COLUMN public.tenant_research_queries.article IS
  '条番号・通達番号（条文/通達サブタブでのみ使う。未指定は NULL）';
